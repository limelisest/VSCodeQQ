import * as vscode from 'vscode';
import assert from 'node:assert/strict';
import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import type { QQApp } from '../src/extension';
import { MockNapCat, until } from './fixture';
import { TestUI } from './ui';

export async function testSettings(app: QQApp, backend: MockNapCat, ui: TestUI, checks: string[]): Promise<void> {
  let view = await ui.webview('.settings-tabs');
  const config = vscode.workspace.getConfiguration('qq'), original = app.config.chatOptions();
  const change = async (id: string, value: string) => view.evaluate(`(() => {const el=document.getElementById(${JSON.stringify(id)});el.value=${JSON.stringify(value)};el.dispatchEvent(new Event('input',{bubbles:true}));})()`);
  const tab = async (page: string) => { await view.evaluate(`document.getElementById('tab-${page}').click()`); };
  try {
    assert.equal(await view.evaluate(`document.querySelectorAll('[role="tab"]').length`), 4);
    await until(async () => await view.evaluate(`document.getElementById('connBadgeText').textContent === '已连接'`));
    assert.ok((await view.evaluate(`document.getElementById('connectionAccount').textContent`)).includes('123456'));
    await tab('appearance');
    assert.equal(await view.evaluate(`document.querySelector('[data-dirty="appearance"]').textContent`), '', '颜色大小写规范化不应误报未保存');
    await tab('connection');
    app.disconnect();
    await until(async () => await view.evaluate(`document.getElementById('connBadge').classList.contains('disconnected')`));
    await change('url', 'invalid-address'); await change('token', 'unsaved-private-token');
    await tab('config'); await change('historyCount', '0');
    await tab('appearance'); await change('mentionColor', '#123456');
    await view.evaluate(`document.getElementById('page-appearance').requestSubmit()`);
    await until(() => vscode.workspace.getConfiguration('qq').get('mentionColor') === '#123456');
    await until(async () => await view.evaluate(`document.querySelector('[data-dirty="appearance"]').textContent === ''`));
    assert.equal(app.config.url, backend.url); assert.equal(app.config.historyCount, original.historyCount);
    assert.equal(await app.config.token(), '');
    await tab('connection');
    assert.equal(await view.evaluate(`document.getElementById('url').value`), 'invalid-address');
    assert.equal(await view.evaluate(`document.getElementById('token').value`), 'unsaved-private-token');
    checks.push('四页独立校验与保存；其他页无效字段和未保存 Token 不影响当前页');
    await change('url', backend.url); await change('token', '');
    await view.evaluate(`document.getElementById('test').click()`);
    await until(async () => await view.evaluate(`document.getElementById('statusMsg').textContent.includes('连接测试成功')`));
    assert.equal(app.client.connected, false);
    assert.equal(await view.evaluate(`document.getElementById('connBadge').classList.contains('connected')`), false);
    await tab('appearance'); await change('replyColor', '#654321');
    await tab('cache');
    await until(async () => await view.evaluate(`document.getElementById('cacheInfo').textContent.includes('MB')`));
    await tab('appearance'); assert.equal(await view.evaluate(`document.getElementById('replyColor').value`), '#654321');
    checks.push('测试连接不更改实际状态，缓存统计和异步连接事件不覆盖未保存配色');
    await tab('config');
    await until(async () => (app.settings as any).context.globalState.get('settingsPage') === 'config');
    (app.settings as any).panel.dispose(); app.settings.open();
    view = await ui.webview('.settings-tabs');
    await until(async () => await view.evaluate(`document.getElementById('tab-config').getAttribute('aria-selected') === 'true'`));
    checks.push('设置页重开后恢复上次页签');
    await tab('appearance');
    assert.equal(await view.evaluate(`document.querySelectorAll('[data-preview]').length`), 9);
    assert.deepEqual(await view.evaluate(`[...document.querySelectorAll('#statusBarButtons input')].map(el=>el.value)`), ['emojis', 'image', 'file', 'forward']);
    await view.evaluate(`for(const el of document.querySelectorAll('#statusBarButtons input')) el.checked=['file','forward'].includes(el.value);document.getElementById('statusBarButtons').dispatchEvent(new Event('change',{bubbles:true}))`);
    await change('ownColor', '#114477'); await change('recalledColor', '#cc2233'); await change('unreadColor', '#336699');
    await view.evaluate(`document.getElementById('page-appearance').requestSubmit()`);
    await until(() => vscode.workspace.getConfiguration('qq').get('unreadColor') === '#336699');
    assert.deepEqual(vscode.workspace.getConfiguration('qq').get('statusBarButtons'), ['file', 'forward']);
    await until(() => vscode.workspace.getConfiguration('workbench').get<Record<string, unknown>>('colorCustomizations', {})['qq.unreadBadge'] === '#336699');
    await until(async () => await view.evaluate(`!document.querySelector('#page-appearance fieldset').disabled`));
    await view.evaluate(`document.querySelector('#page-appearance [data-action="defaults"]').click()`);
    assert.equal(await view.evaluate(`document.getElementById('ownColor').value`), '#389a65');
    assert.deepEqual(await view.evaluate(`[...document.querySelectorAll('#statusBarButtons input:checked')].map(el=>el.value)`), ['emojis', 'image', 'file', 'forward']);
    assert.deepEqual(vscode.workspace.getConfiguration('qq').get('statusBarButtons'), ['file', 'forward'], '恢复入口默认值也需要保存才应用');
    assert.equal(vscode.workspace.getConfiguration('qq').get('ownColor'), '#114477', '恢复默认先留在草稿，保存后才应用');
    const exported = JSON.parse(app.config.exportData());
    assert.equal(exported.format, 'vscode-qq'); assert.equal(exported.settings.ownColor, '#114477');
    assert.deepEqual(exported.settings.statusBarButtons, ['file', 'forward']);
    assert.ok(!JSON.stringify(exported).includes('Token')); assert.ok(!('ws_token' in exported.settings));
    await tab('cache');
    await until(async () => await view.evaluate(`document.getElementById('cacheBreakdown').textContent.includes('接收图片')`));
    assert.ok((await app.cacheInfo()).categories!.some(category => category.name === '最近使用表情'));
    checks.push('九类配色、标签主题色同步、默认值草稿、无 Token 导出和全分类缓存统计验收通过');
    const out = path.join(__dirname, '..', '..', '.test-output'); await fs.mkdir(out, { recursive: true });
    const shot = await ui.call('Page.captureScreenshot', { format: 'png' });
    await fs.writeFile(path.join(out, 'settings-pages.png'), Buffer.from(shot.data, 'base64'));
    await app.connect();
  } finally { for (const [key, value] of Object.entries(original)) await config.update(key, value, vscode.ConfigurationTarget.Global); }
}

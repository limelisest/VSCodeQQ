import * as vscode from 'vscode';
import assert from 'node:assert/strict';
import type { QQApp } from '../src/extension';
import { MockNapCat, until } from './fixture';
import { TestUI } from './ui';
const label = (item: vscode.CompletionItem) => typeof item.label === 'string' ? item.label : item.label.label;
export async function testSlashCommands(app: QQApp, backend: MockNapCat, ui: TestUI, checks: string[]): Promise<void> {
  await app.openChat('private:10001');
  const privateEditor = vscode.window.activeTextEditor!;
  app.store!.setDraft('private:10001', '/', undefined, []);
  await until(() => app.native.draft(privateEditor.document) === '/' && !app.native.isUpdating(privateEditor.document));
  const completions = await vscode.commands.executeCommand<vscode.CompletionList>('vscode.executeCompletionItemProvider', privateEditor.document.uri, privateEditor.document.positionAt(privateEditor.document.getText().length), '/');
  assert.ok(completions.items.some(item => label(item) === '/emoji'));
  assert.ok(!completions.items.some(item => ['/status', '/ban', '/mention', '/manage', '/group_files'].includes(label(item))));
  app.store!.setDraft('private:10001', '', undefined, []);
  checks.push('Slash 菜单只显示常用聊天入口，底层接口不进入候选，私聊隐藏群管理');
  await app.openChat('group:20002');
  const editor = vscode.window.activeTextEditor!;
  app.store!.setDraft('group:20002', '/man', undefined, []);
  await until(() => app.native.draft(editor.document) === '/man' && !app.native.isUpdating(editor.document));
  await app.native.focus(editor);
  await vscode.commands.executeCommand('workbench.action.focusActiveEditorGroup');
  await vscode.commands.executeCommand('editor.action.triggerSuggest');
  await ui.waitFor(`document.querySelector('.suggest-widget.visible')?.textContent.includes('/manage')`);
  const beforeManagement = backend.sent.length;
  await ui.enter();
  await until(() => app.native.draft(editor.document) === '/manage ');
  await ui.waitFor(`document.querySelector('.suggest-widget.visible')?.textContent.includes('ban') && document.querySelector('.suggest-widget.visible')?.textContent.includes('禁言群成员')`);
  assert.equal(backend.sent.length, beforeManagement);
  await vscode.commands.executeCommand('hideSuggestWidget');
  app.store!.setDraft('group:20002', '/manage ba', undefined, []);
  await until(() => app.native.draft(editor.document) === '/manage ba' && !app.native.isUpdating(editor.document));
  await app.native.focus(editor);
  await vscode.commands.executeCommand('editor.action.triggerSuggest');
  await ui.waitFor(`document.querySelector('.suggest-widget.visible')?.textContent.includes('禁言群成员')`);
  await ui.call('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Tab', code: 'Tab', windowsVirtualKeyCode: 9 });
  await ui.call('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Tab', code: 'Tab', windowsVirtualKeyCode: 9 });
  await until(() => app.native.draft(editor.document) === '/manage ban ');
  await ui.waitFor(`document.querySelector('.suggest-widget.visible')?.textContent.includes('@群名片')`);
  await ui.call('Input.insertText', { text: '@群' });
  await ui.waitFor(`document.querySelector('.suggest-widget.visible')?.textContent.includes('@群名片') && !document.querySelector('.suggest-widget.visible')?.textContent.includes('@我的名片')`);
  await ui.call('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Tab', code: 'Tab', windowsVirtualKeyCode: 9 });
  await ui.call('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Tab', code: 'Tab', windowsVirtualKeyCode: 9 });
  await until(() => app.native.draft(editor.document).includes('[@:群名片]'));
  assert.ok(!backend.calls.some(c => c.action === 'set_group_ban'), 'Tab 补全不执行管理操作');
  const commandText = app.native.draft(editor.document);
  await vscode.commands.executeCommand('hideSuggestWidget');
  await ui.enter();
  await ui.waitFor(`document.querySelector('.quick-input-widget')?.textContent.includes('确认操作')`);
  await vscode.commands.executeCommand('workbench.action.closeQuickOpen');
  await until(() => app.native.draft(editor.document) === commandText);
  assert.ok(!backend.calls.some(c => c.action === 'set_group_ban'));
  await ui.enter();
  await ui.waitFor(`document.querySelector('.quick-input-widget')?.textContent.includes('确认操作')`);
  await ui.call('Input.insertText', { text: '确认' });
  await ui.waitFor(`document.querySelector('.quick-input-list')?.textContent.includes('确认') && !document.querySelector('.quick-input-list')?.textContent.includes('取消')`);
  await ui.enter();
  await until(() => backend.calls.some(c => c.action === 'set_group_ban'));
  await until(() => app.native.draft(editor.document) === '');
  assert.deepEqual(backend.calls.find(c => c.action === 'set_group_ban')!.params, { group_id: '20002', user_id: '10001', duration: 1800 });
  assert.equal(backend.sent.length, beforeManagement);
  checks.push('/manage 子命令和成员逐级自动候选，真实 Tab 仅补全，Enter 确认后执行，取消保留草稿且不发送聊天消息');
  await vscode.commands.executeCommand('hideSuggestWidget');
  for (const invalid of ['/manage ban', '/manage ban 10001 -1', '/manage unknown']) {
    app.store!.setDraft('group:20002', invalid, undefined, []);
    await until(() => app.native.draft(editor.document) === invalid && !app.native.isUpdating(editor.document));
    const calls = backend.calls.filter(call => call.action.startsWith('set_group')).length;
    await assert.rejects(async () => { await vscode.commands.executeCommand('qq.send', editor.document.uri.toString()); });
    assert.equal(app.native.draft(editor.document), invalid);
    assert.equal(backend.calls.filter(call => call.action.startsWith('set_group')).length, calls);
    assert.equal(backend.sent.length, beforeManagement);
  }
  checks.push('缺失成员、非法时长和未知子命令均保留草稿，不请求管理接口，也不作为 QQ 消息发送');
  app.store!.setDraft('group:20002', '/status', undefined, []);
  await until(() => app.native.draft(editor.document) === '/status' && !app.native.isUpdating(editor.document));
  await app.native.focus(editor);
  await vscode.commands.executeCommand('hideSuggestWidget');
  const beforeSends = backend.sent.length;
  await ui.enter();
  await until(() => vscode.window.activeTextEditor?.document.uri.scheme === 'qq-result');
  assert.ok(vscode.window.activeTextEditor!.document.getText().includes('"online": true'));
  assert.equal(app.store!.draft('group:20002').text, '');
  assert.equal(backend.sent.length, beforeSends, '/status 不能作为聊天文本发送');
  await vscode.window.tabGroups.close(vscode.window.tabGroups.activeTabGroup.activeTab!);
  await app.openChat('group:20002');
  app.store!.setDraft('group:20002', '操作期间保留草稿', '77990', []);
  await until(() => app.native.draft(editor.document) === app.store!.draft('group:20002').replyPlaceholder + '操作期间保留草稿' && !app.native.isUpdating(editor.document));
  const invocation = app.slash.capture(editor.document.uri)!;
  const cancelledBan = vscode.commands.executeCommand('qq.slash', 'ban', invocation);
  await ui.waitFor(`document.querySelector('.quick-input-widget')?.textContent.includes('选择用户')`);
  await vscode.commands.executeCommand('workbench.action.closeQuickOpen'); await cancelledBan;
  assert.equal(app.store!.draft('group:20002').text, app.store!.draft('group:20002').replyPlaceholder + '操作期间保留草稿');
  assert.equal(app.store!.draft('group:20002').replyId, '77990');
  assert.equal(backend.calls.filter(c => c.action === 'set_group_ban').length, 1);
  const beforeStale = backend.calls.length;
  await assert.rejects(app.slash.run('status', { ...invocation, generation: -1 }), /会话或连接/);
  assert.equal(backend.calls.length, beforeStale);
  checks.push('真实 Enter 执行完整英文指令且不发送到 QQ；取消参数保留草稿和回复，过期补全不能执行');
  const original = app.store!.messages.get('group:20002')!.find(m => m.id === '77990')!;
  const originalSegments = structuredClone(original.segments);
  const recalling = vscode.commands.executeCommand('qq.slash', 'recall', invocation);
  await ui.waitFor(`document.querySelector('.quick-input-widget')?.textContent.includes('选择消息')`);
  await ui.call('Input.insertText', { text: '77990' });
  await ui.waitFor(`document.querySelector('.quick-input-list')?.textContent.includes('77990')`);
  await ui.enter();
  await ui.waitFor(`document.querySelector('.quick-input-widget')?.textContent.includes('确认操作')`);
  await ui.call('Input.insertText', { text: '确认' });
  await ui.waitFor(`document.querySelector('.quick-input-list')?.textContent.includes('确认') && !document.querySelector('.quick-input-list')?.textContent.includes('取消')`);
  await ui.enter();
  await recalling;
  assert.ok(backend.calls.some(c => c.action === 'delete_msg' && c.params.message_id === '77990'));
  assert.equal(app.store!.messages.get('group:20002')!.find(m => m.id === '77990')!.recalled, true);
  assert.deepEqual(app.store!.messages.get('group:20002')!.find(m => m.id === '77990')!.segments, originalSegments);
  backend.emit({ post_type: 'notice', self_id: 123456, notice_type: 'group_recall', group_id: 20002, user_id: 10001, operator_id: 10001, message_id: 77702 });
  await until(() => app.store!.messages.get('group:20002')!.find(m => m.id === '77702')!.recalled === true);
  await until(() => app.transcript!.rendered.get('group:20002')!.recalledLines.length > 0 && editor.document.getText().includes('// 已撤回') && !app.native.isUpdating(editor.document));
  const rendered = app.transcript!.rendered.get('group:20002')!;
  assert.ok(rendered.text.includes('click-body-probe'));
  const start = rendered.starts.get('77990')!;
  const end = rendered.recalledLines.filter(line => rendered.messages.get(line) === '77990').at(-1)!;
  assert.equal(editor.document.lineAt(end).text, '}  // 已撤回');
  assert.ok(!rendered.actions.some(a => a.messageId === '77990' && a.kind === 'reply'));
  assert.ok(!rendered.replyLines.some(line => rendered.messages.get(line) === '77702'));
  await vscode.commands.executeCommand('workbench.action.closeSidebar');
  await vscode.commands.executeCommand('workbench.action.closePanel');
  // Switching to the result document creates a new TextEditor even for the same document.
  const currentEditor = vscode.window.activeTextEditor!;
  app.editor.follow(currentEditor, false);
  currentEditor.revealRange(new vscode.Range(start, 0, end, 0), vscode.TextEditorRevealType.InCenter);
  try { await ui.waitFor(`(() => {
    const root = document.querySelector('.editor-group-container.active .monaco-editor');
    const line = [...(root?.querySelectorAll('.view-line') ?? [])].find(e => e.textContent.includes('click-body-probe'));
    const comment = [...(root?.querySelectorAll('.view-line') ?? [])].find(e => /已撤回/.test(e.textContent));
    const red = element => { const c = getComputedStyle(element).color; return c === 'rgb(241, 76, 76)' || c === 'rgb(180, 35, 24)'; };
    return line && comment && [...line.querySelectorAll('span')].some(e => e.textContent.includes('click-body-probe') && red(e)) && [...comment.querySelectorAll('span')].some(e => e.textContent.includes('已撤回') && red(e));
  })()`); } catch (error) {
    console.error('Recall decoration UI', await ui.evaluate(`(() => {
      const root = document.querySelector('.editor-group-container.active .monaco-editor');
      return [...(root?.querySelectorAll('.view-line') ?? [])].map(e => ({text:e.textContent, spans:[...e.querySelectorAll('span')].map(s => ({text:s.textContent, color:getComputedStyle(s).color, cls:s.className}))}));
    })()`));
    throw error;
  }
  checks.push('撤回成功及远端群撤回保留原文，右花括号后同行注释已撤回；真实编辑器正文和注释均标红且覆盖回复提醒高亮');
  await app.openChat('private:10001');
  backend.emit({ ...backend.message(77991), message_type: 'private', user_id: 10001, sender: { user_id: 10001, nickname: '好友' }, message: [{ type: 'text', data: { text: '私聊撤回原文' } }] });
  await until(() => app.store!.messages.get('private:10001')!.some(m => m.id === '77991'));
  backend.emit({ post_type: 'notice', self_id: 123456, notice_type: 'friend_recall', user_id: 10001, message_id: 77991 });
  const privateDoc = vscode.window.activeTextEditor!.document;
  await until(() => privateDoc.getText().includes('私聊撤回原文') && privateDoc.getText().includes('// 已撤回'));
  assert.equal(app.store!.messages.get('private:10001')!.find(m => m.id === '77991')!.recalled, true);
  checks.push('好友撤回通知同步显示已撤回注释并保留正文');
  await app.openChat('group:20002');
  backend.emit({ post_type: 'request', self_id: 123456, request_type: 'friend', user_id: 10007, flag: 'native-friend-request', comment: '申请测试' });
  await until(() => app.slash.requests.entries('123456').length === 1);
  const handling = vscode.commands.executeCommand('qq.slash', 'requests', invocation);
  await ui.waitFor(`document.querySelector('.quick-input-widget')?.textContent.includes('处理申请')`); await ui.enter();
  await ui.waitFor(`document.querySelector('.quick-input-list')?.textContent.includes('同意')`); await ui.enter();
  await ui.waitFor(`document.querySelector('.quick-input-widget')?.textContent.includes('好友备注')`);
  await ui.call('Input.insertText', { text: '申请备注' }); await ui.enter();
  await ui.waitFor(`document.querySelector('.quick-input-widget')?.textContent.includes('确认操作')`);
  await ui.call('Input.insertText', { text: '确认' });
  await ui.waitFor(`document.querySelector('.quick-input-list')?.textContent.includes('确认') && !document.querySelector('.quick-input-list')?.textContent.includes('取消')`);
  await ui.enter();
  await handling;
  assert.ok(backend.calls.some(c => c.action === 'set_friend_add_request' && c.params.flag === 'native-friend-request' && c.params.approve === true && c.params.remark === '申请备注'));
  assert.equal(app.slash.requests.entries('123456').length, 0);
  checks.push('请求事件进入 /requests，真实选择并确认好友申请后发送原 flag 和备注，成功才移除');
  const browsing = vscode.commands.executeCommand('qq.slash', 'group_files', invocation);
  await ui.waitFor(`document.querySelector('.quick-input-list')?.textContent.includes('测试文件夹')`); await ui.enter();
  await ui.waitFor(`document.querySelector('.quick-input-list')?.textContent.includes('测试文件.txt')`);
  await vscode.commands.executeCommand('workbench.action.closeQuickOpen'); await browsing;
  assert.ok(backend.calls.some(c => c.action === 'get_group_files_by_folder' && c.params.group_id === '20002' && c.params.folder_id === 'mock-folder'));
  assert.equal(app.store!.draft('group:20002').text, app.store!.draft('group:20002').replyPlaceholder + '操作期间保留草稿');
  assert.equal(backend.sent.length, beforeSends);
  checks.push('/group_files 真实浏览根目录和文件夹，取消不下载、不发送、不改变草稿');
}

import * as vscode from 'vscode';
import assert from 'node:assert/strict';
import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import type { QQApp } from '../src/extension';
import { MockNapCat, until } from './fixture';
import { TestUI } from './ui';
import { basicFaces } from '../src/attachments';

export async function testEmojiOrder(app: QQApp, backend: MockNapCat, ui: TestUI, checks: string[]): Promise<void> {
  const sent = backend.sent.length, originalBackend = backend.appName;
  const context = (app.emojis as any).context as vscode.ExtensionContext;
  const recentKey = `recentEmojis.${app.store!.selfId}`, originalRecent = context.globalState.get(recentKey);
  await context.globalState.update(recentKey, basicFaces.slice(0, 10).map(face => ({ id: `face:${face.id}`, kind: 'face', label: face.name, faceId: face.id })));
  const open = async () => {
    const before = backend.calls.filter(call => call.action === 'fetch_custom_face').length;
    await app.openChat('group:20002'); await vscode.commands.executeCommand('qq.emojis');
    const view = await ui.webview('#favoriteFaces');
    await until(() => backend.calls.filter(call => call.action === 'fetch_custom_face').length > before);
    await until(async () => await view.evaluate(`!document.getElementById('emojiOrder').disabled && document.querySelectorAll('#favoriteFaces button').length >= 2`));
    return view;
  };
  let view = await open();
  const setOrder = async (order: string) => {
    await view.evaluate(`(() => {const el=document.getElementById('emojiOrder');el.value=${JSON.stringify(order)};el.dispatchEvent(new Event('change'));})()`);
    await until(() => { const pref = (app.emojis as any).preference; return pref && (app.emojis as any).context.globalState.get(pref.key) === order; });
  };
  const firstUrl = async () => (app.emojis as any).favoriteSources.get(await view.evaluate(`document.querySelector('#favoriteFaces button').dataset.id`))?.url;
  try {
    assert.equal(await view.evaluate(`document.getElementById('tabRecent') === null && !document.getElementById('recentFaces').hidden`), true);
    await setOrder('reverse'); assert.equal(await firstUrl(), backend.imageUrl + '?second');
    const beforeReload = backend.calls.filter(call => call.action === 'fetch_custom_face').length;
    await view.evaluate(`document.getElementById('reloadFaces').click()`);
    await until(() => backend.calls.filter(call => call.action === 'fetch_custom_face').length > beforeReload);
    await until(async () => await view.evaluate(`!document.getElementById('emojiOrder').disabled && document.getElementById('favoriteStatus').hidden`));
    assert.equal(await firstUrl(), backend.imageUrl + '?second');
    await view.key('Escape', 27); await until(() => !(app.emojis as any).view?.visible); view = await open();
    await until(async () => await view.evaluate(`document.getElementById('emojiOrder').value === 'reverse'`));
    assert.equal(await firstUrl(), backend.imageUrl + '?second');
    checks.push('合并最近与收藏列表，排序选择在刷新和关闭重开后保持');
    backend.appName = 'MockOtherBackend'; backend.favoriteUrls = [backend.imageUrl + '?second', backend.imageUrl];
    app.disconnect(); await app.connect(); view = await open();
    assert.equal(await view.evaluate(`document.getElementById('emojiOrder').value`), 'original');
    await setOrder('original');
    backend.appName = originalBackend; backend.favoriteUrls = undefined;
    app.disconnect(); await app.connect(); view = await open();
    assert.equal(await view.evaluate(`document.getElementById('emojiOrder').value`), 'reverse');
    checks.push('同账号、同服务地址更换后端时分别记忆，切回原后端恢复原排序');
    backend.favoriteUrls = Array.from({ length: 620 }, (_, i) => backend.imageUrl + '?emoji=' + i);
    const fetchCount = () => backend.calls.filter(call => call.action === 'fetch_custom_face').length;
    const beforeRefresh = fetchCount();
    await view.evaluate(`document.getElementById('reloadFaces').click()`);
    await until(async () => await firstUrl() === backend.imageUrl + '?emoji=619');
    assert.equal(await view.evaluate(`document.querySelectorAll('#favoriteFaces button').length`), 48);
    const displayedUrls = async () => (await view.evaluate(`Array.from(document.querySelectorAll('#favoriteFaces button'),button=>button.dataset.id)`)).map((id: string) => (app.emojis as any).favoriteSources.get(id)?.url);
    assert.deepEqual(await displayedUrls(), backend.favoriteUrls.slice().reverse().slice(0, 48));
    assert.deepEqual(backend.calls.filter(call => call.action === 'fetch_custom_face').slice(beforeRefresh).map(call => call.params.count), [512, 1024]);
    const afterRefresh = fetchCount();
    assert.equal(await view.evaluate(`document.getElementById('moreFaces') === null`), true, '移除手动翻页按钮');
    await view.evaluate(`(() => {const button=Array.from(document.querySelectorAll('#favoriteFaces button')).at(-1);button.dataset.probe='kept';button.focus({preventScroll:true});})()`);
    await view.key('ArrowRight', 39);
    assert.equal(await view.evaluate(`Array.from(document.querySelectorAll('#favoriteFaces button')).indexOf(document.activeElement)`), 48, '向右越过首批末项，继续选中下一批第一项');
    assert.ok((await displayedUrls()).length >= 96);
    await view.key('ArrowLeft', 37);
    assert.equal(await view.evaluate(`document.activeElement.dataset.probe`), 'kept', '追加不重建已有按钮');
    const downTarget = await view.evaluate(`(() => {const buttons=Array.from(document.querySelectorAll('#favoriteFaces button'));const columns=buttons.filter(b=>b.offsetTop===buttons[0].offsetTop).length;buttons.at(-1).focus({preventScroll:true});return buttons.length-1+columns;})()`);
    await view.key('ArrowDown', 40);
    assert.equal(await view.evaluate(`Array.from(document.querySelectorAll('#favoriteFaces button')).indexOf(document.activeElement)`), downTarget, '向下越过当前批次最后一行，保持列位置进入下一批');
    checks.push('方向键跨批次连续选择，向右进入下一项、向下保持列位置，向左可返回且不重建已有按钮');
    const beforeScroll = await view.evaluate(`({count:document.querySelectorAll('#favoriteFaces button').length,selected:document.activeElement.dataset.id})`);
    await view.evaluate(`document.getElementById('stickerList').scrollTop=document.getElementById('stickerList').scrollHeight`);
    await until(async () => await view.evaluate(`document.querySelectorAll('#favoriteFaces button').length > ${beforeScroll.count}`));
    assert.equal(await view.evaluate(`document.activeElement.dataset.id`), beforeScroll.selected, '滚动触底追加时保留键盘焦点');
    assert.ok(await view.evaluate(`document.getElementById('stickerList').scrollTop > 0`), '追加时不能跳回顶部');
    let displayed = await displayedUrls();
    assert.deepEqual(displayed, backend.favoriteUrls.slice().reverse().slice(0, displayed.length));
    assert.equal(fetchCount(), afterRefresh, '自动翻页只展开同一完整快照，不能重新截取并反转前缀');
    checks.push('滚动触底自动追加下一批，保留焦点和滚动位置，不重复请求收藏列表');
    await setOrder('original');
    assert.deepEqual(await displayedUrls(), backend.favoriteUrls.slice(0, displayed.length));
    await setOrder('reverse');
    assert.deepEqual(await displayedUrls(), backend.favoriteUrls.slice().reverse().slice(0, displayed.length));
    while (displayed.length < 620) {
      const before = displayed.length;
      await view.evaluate(`document.getElementById('stickerList').scrollTop=document.getElementById('stickerList').scrollHeight`);
      await until(async () => await view.evaluate(`document.querySelectorAll('#favoriteFaces button').length > ${before}`));
      displayed = await displayedUrls();
    }
    assert.equal(await view.evaluate(`document.querySelectorAll('#favoriteFaces button').length`), 620);
    assert.deepEqual(await displayedUrls(), backend.favoriteUrls.slice().reverse());
    await view.evaluate(`document.getElementById('stickerList').scrollTop=document.getElementById('stickerList').scrollHeight`);
    await view.evaluate(`Array.from(document.querySelectorAll('#favoriteFaces button')).at(-1).focus({preventScroll:true})`);
    await view.key('End', 35); await view.key('ArrowRight', 39); await view.key('ArrowDown', 40);
    assert.equal(await view.evaluate(`document.querySelectorAll('#favoriteFaces button').length`), 620, '最后一批不重复追加');
    assert.equal(fetchCount(), afterRefresh);
    checks.push('620 张收藏先完整读取再全局排序，分页和切换顺序均连续，全部可展开且没有 500 张截断');
    const layout = await view.evaluate(`(() => {const list=document.getElementById('stickerList');list.style.width='250px';list.scrollTop=0;const recent=document.getElementById('recentSection'),favorites=document.getElementById('favoriteSection');const top=recent.getBoundingClientRect().top, favoriteTop=favorites.getBoundingClientRect().top;list.scrollTop=180;return {scroll:list.scrollTop,recentMoved:top-recent.getBoundingClientRect().top,favoritesMoved:favoriteTop-favorites.getBoundingClientRect().top,wrap:document.querySelectorAll('#recentFaces button')[9].offsetTop>document.querySelector('#recentFaces button').offsetTop,innerScrollable:['recentSection','favoriteSection','recentFaces','favoriteFaces'].some(id=>['auto','scroll'].includes(getComputedStyle(document.getElementById(id)).overflowY)),overflow:list.scrollWidth>list.clientWidth};})()`);
    assert.ok(layout.scroll > 0); assert.ok(Math.abs(layout.recentMoved - layout.scroll) < 1); assert.ok(Math.abs(layout.favoritesMoved - layout.scroll) < 1);
    assert.equal(layout.wrap, true, '最近使用与收藏采用相同网格换行'); assert.equal(layout.innerScrollable, false); assert.equal(layout.overflow, false);
    await view.evaluate(`document.getElementById('stickerList').style.width=''; document.getElementById('stickerList').scrollTop=0; Array.from(document.querySelectorAll('#recentFaces button')).at(-1).focus()`);
    await view.key('ArrowDown', 40);
    assert.equal(await view.evaluate(`document.activeElement.parentElement.id`), 'favoriteFaces');
    await view.key('ArrowUp', 38);
    assert.equal(await view.evaluate(`document.activeElement.parentElement.id`), 'recentFaces');
    assert.equal(await view.evaluate(`document.activeElement.offsetTop === Array.from(document.querySelectorAll('#recentFaces button')).at(-1).offsetTop`), true, '向上跨标题返回最近使用最后一行');
    await view.key('End', 35);
    assert.equal(await view.evaluate(`document.activeElement === Array.from(document.querySelectorAll('#favoriteFaces button')).at(-1)`), true);
    await view.key('Home', 36);
    assert.equal(await view.evaluate(`document.activeElement === document.querySelector('#recentFaces button')`), true);
    await view.key('Escape', 27); await until(() => !(app.emojis as any).view?.visible); view = await open();
    assert.equal(await firstUrl(), backend.imageUrl + '?emoji=619');
    assert.equal(await view.evaluate(`document.getElementById('stickerList').scrollTop === 0 && document.activeElement === document.querySelector('#recentFaces button')`), true);
    await view.evaluate(`document.querySelector('#favoriteFaces button').scrollIntoView({block:'nearest'})`);
    await until(async () => await view.evaluate(`document.querySelector('#favoriteFaces img')?.naturalWidth > 0`));
    await view.evaluate(`document.getElementById('stickerList').scrollTop=0`);
    assert.equal(await view.evaluate(`document.querySelector('#recentSection .emoji-heading').getBoundingClientRect().top >= document.querySelector('nav').getBoundingClientRect().bottom`), true, '自动聚焦不得滚走最近使用标题');
    const shot = await ui.call('Page.captureScreenshot', { format: 'png' });
    const folder = path.join(__dirname, '..', '..', '.test-output'); await fs.mkdir(folder, { recursive: true }); await fs.writeFile(path.join(folder, 'emoji-combined.png'), Buffer.from(shot.data, 'base64'));
    checks.push('最近与收藏共用一个滚动列表，最近排最前并换行，标题隔行、跨标题方向键和重开定位均可用');
    backend.favoriteIgnoreCount = true;
    backend.favoriteUrls = Array.from({ length: 620 }, (_, i) => backend.imageUrl + '?ignored=' + i);
    const beforeIgnoredRefresh = fetchCount();
    await view.evaluate(`document.getElementById('reloadFaces').click()`);
    await until(async () => await firstUrl() === backend.imageUrl + '?ignored=619');
    assert.equal(fetchCount() - beforeIgnoredRefresh, 2);
    assert.deepEqual(await displayedUrls(), backend.favoriteUrls.slice().reverse().slice(0, 48));
    checks.push('兼容忽略 count、一次返回全部收藏的后端，仍按完整列表排序');
    app.disconnect();
    await until(async () => await view.evaluate(`document.querySelectorAll('#recentFaces button').length > 0 && document.getElementById('emojiOrder').disabled`));
    assert.equal(backend.sent.length, sent);
    checks.push('断线后仍能显示本地最近表情，全部验收不向 QQ 发送消息');
  } finally { await context.globalState.update(recentKey, originalRecent); backend.appName = originalBackend; backend.favoriteUrls = undefined; backend.favoriteIgnoreCount = false; if (!app.ready) await app.connect(); }
}
